import 'package:flutter/material.dart';
import 'package:firebase_core/firebase_core.dart';
import 'package:provider/provider.dart';
import 'firebase_options.dart'; // Generated by: flutterfire configure
import 'providers/auth_provider.dart';
import 'providers/item_provider.dart';
import 'screens/auth/login_screen.dart';
import 'screens/home/home_screen.dart';

Future<void> main() async {
  // Ensure Flutter binding is ready before calling native code
  WidgetsFlutterBinding.ensureInitialized();

  // Initialize Firebase using the generated firebase_options.dart
  await Firebase.initializeApp(
    options: DefaultFirebaseOptions.currentPlatform,
  );

  runApp(
    // Wrap the entire app in MultiProvider so any widget can access shared state
    MultiProvider(
      providers: [
        ChangeNotifierProvider(create: (_) => AuthProvider()),
        ChangeNotifierProvider(create: (_) => ItemProvider()),
      ],
      child: const FindItApp(),
    ),
  );
}

class FindItApp extends StatelessWidget {
  const FindItApp({super.key});

  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      title: 'FindIt BSU',
      debugShowCheckedModeBanner: false,

      // ── Material 3 Theme ────────────────────────────────────────────────
      // BSU Alangilan brand color: deep maroon / red
      theme: ThemeData(
        useMaterial3: true,
        colorScheme: ColorScheme.fromSeed(
          seedColor: const Color(0xFF8B0000), // BSU maroon
          brightness: Brightness.light,
        ),
        // Use a clean, modern font feel (falls back to Roboto on Android)
        textTheme: const TextTheme().apply(
          fontSizeFactor: 1.0,
        ),
        inputDecorationTheme: InputDecorationTheme(
          filled: true,
          // Light fill so fields stand out on the card background
          fillColor: Colors.transparent,
          contentPadding:
              const EdgeInsets.symmetric(horizontal: 16, vertical: 14),
        ),
        appBarTheme: const AppBarTheme(
          centerTitle: false,
          elevation: 0,
          scrolledUnderElevation: 1,
        ),
      ),

      // ── Auth Gate ────────────────────────────────────────────────────────
      // Watches AuthProvider to decide which screen to show.
      // Firebase Auth persists the session, so _onAuthStateChanged in
      // AuthProvider automatically restores the user on every app launch.
      home: const _AuthGate(),
    );
  }
}

/// Listens to [AuthProvider] and routes to [LoginScreen] or [PlaceholderHomeScreen].
/// Displays a loading spinner while the initial auth state is being resolved.
class _AuthGate extends StatelessWidget {
  const _AuthGate();

  @override
  Widget build(BuildContext context) {
    final authProvider = context.watch<AuthProvider>();

    // Show a splash/loading screen ONLY on cold start while checking saved session.
    // This ensures LoginScreen is not destroyed/cleared during login submissions.
    if (authProvider.isInitialLoading) {
      return const Scaffold(
        body: Center(child: CircularProgressIndicator()),
      );
    }

    if (authProvider.isLoggedIn) {
      return const HomeScreen();
    }

    return const LoginScreen();
  }
}
